-- Схема Hotel Management Service (H2, в памяти). Hibernate только проверяет её (ddl-auto=validate).

CREATE TABLE hotels
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150)             NOT NULL,
    city       VARCHAR(100)             NOT NULL,
    address    VARCHAR(255)             NOT NULL,
    stars      INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_hotels_stars CHECK (stars IS NULL OR stars BETWEEN 1 AND 5)
);

CREATE INDEX idx_hotels_city ON hotels (city);

CREATE TABLE rooms
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id        BIGINT                   NOT NULL,
    number          VARCHAR(20)              NOT NULL,
    type            VARCHAR(20)              NOT NULL,
    capacity        INTEGER                  NOT NULL,
    price_per_night NUMERIC(10, 2)           NOT NULL,
    -- эксплуатационная доступность (ремонт); занятость по датам хранится в room_reservations
    available       BOOLEAN                  NOT NULL DEFAULT TRUE,
    -- статистика для алгоритма рекомендаций
    times_booked    BIGINT                   NOT NULL DEFAULT 0,
    -- оптимистическая блокировка
    version         BIGINT                   NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_rooms_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id) ON DELETE CASCADE,
    CONSTRAINT uq_rooms_hotel_number UNIQUE (hotel_id, number),
    CONSTRAINT ck_rooms_type CHECK (type IN ('STANDARD', 'DELUXE', 'SUITE')),
    CONSTRAINT ck_rooms_capacity CHECK (capacity > 0),
    CONSTRAINT ck_rooms_price CHECK (price_per_night >= 0),
    CONSTRAINT ck_rooms_times_booked CHECK (times_booked >= 0)
);

-- порядок рекомендаций: ORDER BY times_booked, id
CREATE INDEX idx_rooms_times_booked ON rooms (times_booked, id);

CREATE TABLE room_reservations
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT                   NOT NULL,
    booking_id  BIGINT                   NOT NULL,
    -- ключ идемпотентности шага саги «подтверждение доступности»
    request_id  VARCHAR(100)             NOT NULL,
    start_date  DATE                     NOT NULL,
    end_date    DATE                     NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_reservations_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT uq_reservations_request UNIQUE (request_id),
    CONSTRAINT ck_reservations_period CHECK (end_date > start_date),
    CONSTRAINT ck_reservations_status CHECK (status IN ('HELD', 'RELEASED'))
);

-- проверка пересечений: room_id = ? AND status = 'HELD' AND start_date < ? AND end_date > ?
CREATE INDEX idx_reservations_room_period ON room_reservations (room_id, status, start_date, end_date);
CREATE INDEX idx_reservations_booking ON room_reservations (booking_id);
