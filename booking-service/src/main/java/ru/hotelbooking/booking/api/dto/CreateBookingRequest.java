package ru.hotelbooking.booking.api.dto;

import com.fasterxml.jackson.annotation.JsonIgnore;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.FutureOrPresent;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import java.time.LocalDate;
import java.util.UUID;
import ru.hotelbooking.common.validation.DateRangeAware;
import ru.hotelbooking.common.validation.ValidDateRange;

/**
 * Запрос на бронирование. Проживание — полуоткрытый интервал {@code [startDate, endDate)} не длиннее 30 ночей.
 */
@ValidDateRange(maxDays = 30)
public record CreateBookingRequest(
        @Schema(
                description = "Idempotency key generated by the client; repeat it when retrying the same booking",
                example = "3f1c2d4e-5b6a-4c7d-8e9f-0a1b2c3d4e5f")
        @NotNull
        UUID requestId,

        @Schema(description = "Pick the least booked free room automatically; roomId is ignored when true")
        boolean autoSelect,

        @Schema(description = "Room to book; required when autoSelect is false", example = "3")
        Long roomId,

        @Schema(description = "Restrict automatic selection to one hotel", example = "1") @Positive
        Long hotelId,

        @Schema(description = "Check-in date", example = "2030-01-10") @NotNull @FutureOrPresent
        LocalDate startDate,

        @Schema(description = "Check-out date (exclusive)", example = "2030-01-12") @NotNull
        LocalDate endDate)
        implements DateRangeAware {

    /** По ТЗ при {@code autoSelect = true} поле {@code roomId} игнорируется, поэтому и проверяется только без него. */
    @JsonIgnore
    @Schema(hidden = true)
    @AssertTrue(message = "roomId must be a positive room id when autoSelect is false")
    public boolean isRoomSpecified() {
        return autoSelect || (roomId != null && roomId > 0);
    }
}
