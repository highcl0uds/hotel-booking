-- Схема Booking Service (H2, в памяти). Hibernate только проверяет её (ddl-auto=validate).

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)              NOT NULL,
    -- BCrypt-хеш
    password   VARCHAR(100)             NOT NULL,
    role       VARCHAR(20)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE bookings
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT                   NOT NULL,
    -- клиентский ключ идемпотентности; уникален в пределах пользователя
    request_id           UUID                     NOT NULL,
    -- NULL, пока автоподбор не выбрал номер
    room_id              BIGINT,
    hotel_id             BIGINT,
    auto_select          BOOLEAN                  NOT NULL DEFAULT FALSE,
    start_date           DATE                     NOT NULL,
    end_date             DATE                     NOT NULL,
    status               VARCHAR(20)              NOT NULL,
    cancel_reason        VARCHAR(40),
    -- TRUE, пока компенсирующее освобождение ещё нужно доставить в Hotel Service
    compensation_pending BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    -- оптимистическая блокировка; увеличивается при каждом переходе статуса
    version              BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_bookings_user_request UNIQUE (user_id, request_id),
    CONSTRAINT ck_bookings_period CHECK (end_date > start_date),
    CONSTRAINT ck_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_bookings_confirmed_room CHECK (status <> 'CONFIRMED' OR room_id IS NOT NULL)
);

-- история броней пользователя: WHERE user_id = ? ORDER BY created_at DESC
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at);
-- фоновая задача восстановления: WHERE status = 'PENDING' AND created_at < ?
CREATE INDEX idx_bookings_status_created ON bookings (status, created_at);
CREATE INDEX idx_bookings_room_period ON bookings (room_id, start_date, end_date);

CREATE TABLE booking_status_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  BIGINT                   NOT NULL,
    -- NULL при создании брони
    from_status VARCHAR(20),
    to_status   VARCHAR(20)              NOT NULL,
    reason      VARCHAR(40),
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_history_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE
);

CREATE INDEX idx_history_booking ON booking_status_history (booking_id, changed_at);
